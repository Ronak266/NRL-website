"""Build a local-file-safe classic viewer and a truly self-contained HTML preview."""
from pathlib import Path
import base64,re
ROOT=Path(__file__).resolve().parents[1]
geometry=(ROOT/'assets/robot-geometry.js').read_text().replace('export ','')
model=(ROOT/'assets/robot.json').read_text().strip()
runtime=(ROOT/'assets/viewer-runtime.js').read_text()
bundle='/* Generated by scripts/build-preview.py. */\n(()=>{\nconst parts='+model+';\n'+geometry+'\n'+runtime+'\n})();\n'
(ROOT/'assets/portable-viewer.js').write_text(bundle)
html=(ROOT/'index.html').read_text()
html=html.replace('<script src="assets/portable-viewer.js"></script>','<script>'+bundle.replace('</script','<\\/script')+'</script>')
def embed(m):
 attr,path=m.group(1),m.group(2);suffix=Path(path).suffix
 mime={'.svg':'image/svg+xml','.jpg':'image/jpeg','.mp4':'video/mp4'}.get(suffix)
 if not mime:return m.group(0)
 encoded=base64.b64encode((ROOT/path).read_bytes()).decode()
 return attr+'="data:'+mime+';base64,'+encoded+'"'
html=re.sub(r'(src|poster|href)="(assets/[^\"]+)"',embed,html)
# Embed fonts as well, preserving the exact layout offline.
html=re.sub(r"url\('(?P<path>assets/[^']+\.ttf)'\)",lambda m:"url('data:font/ttf;base64,"+base64.b64encode((ROOT/m['path']).read_bytes()).decode()+"')",html)
assert 'type="module"' not in html
assert 'src="assets/' not in html
assert 'fetch(' not in html
(ROOT/'Titan-Forge-Preview.html').write_text(html)
print('Built portable viewer and standalone HTML: model, video and poster embedded.')
