"""Build a local-file-safe classic viewer and a truly self-contained HTML preview."""
from pathlib import Path
import base64,re,hashlib,json
ROOT=Path(__file__).resolve().parents[1]
geometry=(ROOT/'assets/robot-geometry.js').read_text().replace('export ','')
model=(ROOT/'assets/robot.json').read_text().strip()
runtime='\n'.join((ROOT/'assets'/name).read_text().replace('export ','') for name in ['studio-renderer.js','viewer-runtime.js','arena-physics.js','arena-presentation.js','arena-runtime.js','experience-runtime.js','mechanism-runtime.js','cinematic-runtime.js','navigation-runtime.js','anime-runtime.js'])
three=(ROOT/'assets/three.module.js').read_text().replace('\t\t\t \tmaterial', '\t\t\t\tmaterial')
exports=re.search(r'export \{ (.*?) \};',three,re.S).group(1)
three=re.sub(r'export \{ .*? \};','',three,flags=re.S)
three='const THREE=(()=>{'+three+';return {'+exports+'};})();\n'
bundle='/* Generated by scripts/build-preview.py. */\n(()=>{\nconst parts='+model+';\n'+geometry+'\n'+three+runtime+'\n})();\n'
(ROOT/'assets/portable-viewer.js').write_text(bundle)
html=(ROOT/'index.html').read_text()
part_count=len(json.loads(model));wire_count=sum(p.get('wire',False) for p in json.loads(model))
html=re.sub(r'(<div class="part-total"><b>)\d+',lambda m:m[1]+str(part_count),html)
html=re.sub(r'(All systems <span>)\d+',lambda m:m[1]+str(part_count),html)
html=re.sub(r'All \d+ components',f'All {part_count} components',html)
html=re.sub(r'\d+ components separated',f'{part_count} components separated',html)
html=re.sub(r'\d+ INDIVIDUAL WIRES',f'{wire_count} INDIVIDUAL WIRES',html)
html=re.sub(r'(Individual wires <span>)\d+',lambda m:m[1]+str(wire_count),html)
html=re.sub(r'\d+ individual curved wires',f'{wire_count} individual curved wires',html)

html=re.sub(r'<style>.*?</style>',lambda m:'<style>'+(ROOT/'assets/cinematic.css').read_text()+'</style>',html,flags=re.S)
version=hashlib.sha256(bundle.encode()).hexdigest()[:12]
html=re.sub(r'<script src="assets/portable-viewer.js(?:\?v=[a-f0-9]+)?"></script>',lambda m:'<script src="assets/portable-viewer.js?v='+version+'"></script>',html)
(ROOT/'index.html').write_text(html)
html=re.sub(r'<script src="assets/portable-viewer.js(?:\?v=[a-f0-9]+)?"></script>',lambda m:'<script>'+bundle.replace('</script','<\\/script')+'</script>',html)
html=html.replace('<script src="assets/boot-runtime.js"></script>','<script>'+(ROOT/'assets/boot-runtime.js').read_text()+'</script>')
def embed(m):
 attr,path=m.group(1),m.group(2);suffix=Path(path).suffix
 mime={'.svg':'image/svg+xml','.jpg':'image/jpeg','.png':'image/png','.mp4':'video/mp4'}.get(suffix)
 if not mime:return m.group(0)
 encoded=base64.b64encode((ROOT/path).read_bytes()).decode()
 return attr+'="data:'+mime+';base64,'+encoded+'"'
html=html.replace('href="assets/forge-simulation.mp4" download','href="#" download')
# Team photos are referenced from JavaScript data, so embed those paths too.
def embed_team_photo(m):
 quote,path=m.group(1),m.group(2)
 mime='image/png' if Path(path).suffix=='.png' else 'image/jpeg'
 return quote+'data:'+mime+';base64,'+base64.b64encode((ROOT/path).read_bytes()).decode()+quote
html=re.sub(r"([\"'])(assets/team/[^\"']+\.(?:jpg|jpeg|png))\1",embed_team_photo,html)
html=html.replace("image.src='assets/manga-titan.svg'","image.src='data:image/svg+xml;base64,"+base64.b64encode((ROOT/'assets/manga-titan.svg').read_bytes()).decode()+"'")
html=re.sub(r'(src|poster|href)="(assets/[^\"]+)"',embed,html)
# Embed the shared comic artwork once, including CSS background images.
html=re.sub(r"url\('(?P<path>assets/[^']+\.(?:jpg|png|svg))'\)",lambda m:"url('data:"+{'.jpg':'image/jpeg','.png':'image/png','.svg':'image/svg+xml'}[Path(m['path']).suffix]+";base64,"+base64.b64encode((ROOT/m['path']).read_bytes()).decode()+"')",html)
# Embed fonts as well, preserving the exact layout offline.
html=re.sub(r"url\('(?P<path>assets/[^']+\.ttf)'\)",lambda m:"url('data:font/ttf;base64,"+base64.b64encode((ROOT/m['path']).read_bytes()).decode()+"')",html)
assert 'type="module"' not in html
assert 'src="assets/' not in html
assert 'fetch(' not in runtime
(ROOT/'Titan-Forge-Preview.html').write_text(html)
print('Built portable viewer and standalone HTML: model, video and poster embedded.')
